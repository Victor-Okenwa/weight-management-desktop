/**
 * Writes the client update token into a generated module before packaging.
 * Set UPDATE_GH_TOKEN (fine-grained PAT, Contents: Read on the release repo only).
 * Empty token is allowed for local unpackaged builds; packaged private updates need it.
 */
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const outPath = join(__dirname, '../src/updater/update-token.generated.ts');
const token = process.env.UPDATE_GH_TOKEN ?? '';

const contents = `// Generated by scripts/inject-update-token.mjs — do not edit by hand.
// Token is a read-only GitHub PAT baked into the binary for private release downloads.
// Prefer rotating a fine-grained Contents:Read token; long-term migrate to a license-gated feed.
export const UPDATE_GH_TOKEN = ${JSON.stringify(token)};
`;

writeFileSync(outPath, contents, 'utf8');
console.log(
  token
    ? '[inject-update-token] Wrote UPDATE_GH_TOKEN (length ' + token.length + ')'
    : '[inject-update-token] Wrote empty UPDATE_GH_TOKEN (private updates will fail until set)',
);
